def compose(spec, bases, unknown):
    """رموزٌ ← جملةٌ مشكولة. الرمزُ الذي لا أصلَ له يُسجَّل ويُترك كما هو."""
    words = []
    for token in spec.split():
        try:
            words.append(render(token, bases))
        except KeyError as e:
            unknown.append((str(e.args[0]), spec))
            words.append(token)
    return " ".join(words)


def build(data):
    """من الرموز إلى جملٍ مشكولة — وأي كلمة أساسٍ غير معلَنة توقف البناء."""
    bases = all_bases(data)
    unknown = []
    out = [{"text": compose(spec, bases, unknown), "word": target} for target, spec in SPECS]
    return out, unknown


def build_word_sentences(data):
    """جملُ المثال التي يملكها المولّد: كلمةُ المعجم ← جملتُها المشتقّة."""
    bases = all_bases(data)
    unknown = []
    out = {word: compose(spec, bases, unknown) for word, spec in WORD_SPECS.items()}
    return out, unknown


def merged_support(data, sentences):
    """المساند بعد الزيادة: المعلَن + زيادةُ الحزمة، **مطروحاً منه ما لا تستعمله جملة**.

    لا يُجمع جمعاً أعمى: يُعلَن ثم يُشتقّ بـ`support_texts` نفسِها التي يفرضها الفاحص،
    فمفردةٌ حذفتُها من التأليف تخرج من المعلَن في اللحظة نفسِها (لا معجم ميت).
    """
    declared = dict(data)
    declared[SUPPORT_FIELD] = sorted(set(data.get(SUPPORT_FIELD) or []) | set(SUPPORT_ADD))
    declared[SENTENCE_FIELD] = sentences
    return support_texts(declared, taught_words())


def with_sentences(data, sentences):
    """نسخة من بيانات المعجم وفيها `sentences` بعد `words` مباشرةً (وترتيبٌ ثابت)،
    وجملُ المثال التي يملكها المولّد مكتوبةً في كلماتها."""
    owned, _unknown = build_word_sentences(data)
    out = {}
    for key, value in data.items():
        if key in (SUPPORT_FIELD, SENTENCE_FIELD):
            continue
        out[key] = ([{**w, "sentence": owned.get(w.get("word"), w.get("sentence"))} for w in value]
                    if key == "words" else value)
        if key == "words":
            out[SENTENCE_FIELD] = sentences
    out.setdefault(SENTENCE_FIELD, sentences)
    # المساند يُشتقّ من **الجمل بعد التعديل** ومن المعلَن الأصلي معاً
    out[SUPPORT_FIELD] = merged_support({**out, SUPPORT_FIELD: data.get(SUPPORT_FIELD) or []},
                                        sentences)
    return out


def report(sentences, unknown):
    by_len = {}
    for entry in sentences:
        by_len[len(entry["text"].split())] = by_len.get(len(entry["text"].split()), 0) + 1
    print(f"الجمل المؤلَّفة: {len(sentences)} | "
          + "، ".join(f"{n} كلمات: {c}" for n, c in sorted(by_len.items())))
    if unknown:
        print(f"\nكلماتُ أساسٍ غير معلَنة ({len(set(u for u, _ in unknown))}):")
        for base in sorted({u for u, _ in unknown}):
            print(f"  ✗ {base}")
        return 1
    return 0


def self_test(data):
    """المشتقّ مقيسٌ على المادة المعتمدة: صيغ «الـ» في جمل الحزمة ٧ كلها."""
    fails = 0

    def ok(cond, msg):
        nonlocal fails
        if not cond:
            fails += 1
        print(("  ✓ " if cond else "  ✗ ") + msg)

    by_stem = {stem(w["word"]): w["word"] for w in data["words"]}
    hits, misses = 0, []
    for entry in data["words"]:
        for token in entry["sentence"].split():
            base = by_stem.get(stem(token))
            if not base or token == base:
                continue
            mark = token[-1] if token[-1] in END_MARKS else ""
            if definite(base, mark) == token:
                hits += 1
            else:
                misses.append((token, definite(base, mark)))
    ok(not misses and hits > 200,
       f"اشتقاق «الـ» يعيد بناء {hits} صيغة من جمل الحزمة ٧ حرفاً بحرف"
       + (f" — يخالف: {misses[:3]}" if misses else ""))

    ok(definite("سَرِيرْ", DAMMA) == "السَّرِيرُ",
       f"والشمسيّ يُدغَم: سَرِيرْ ← {definite('سَرِيرْ', DAMMA)}")
    ok(definite("غُرْفَةْ", DAMMA) == "الْغُرْفَةُ",
       f"والقمريّ بلامٍ ساكنة: غُرْفَةْ ← {definite('غُرْفَةْ', DAMMA)}")
    ok(definite("لَحْمْ", DAMMA) == "اللَّحْمُ",
       f"واللام في اللام: لَحْمْ ← {definite('لَحْمْ', DAMMA)}")
    ok(definite("قَلَمٌ", SUKUN) == "الْقَلَمْ",
       "وتنوينُ كلمةِ المنهج يسقط عند التعريف (قَلَمٌ ← الْقَلَمْ)")
    ok(raised("تَنَامْ") == "تَنَامُ" and raised("يَمْشِي") == "يَمْشِي"
       and raised("تَقْطَعُ") == "تَقْطَعُ",
       "والفعل يُرفع في وسط الجملة، والمعتلُّ الآخر لا يتغيّر")
    ok(possessed("أُذُنْ") == "أُذُنِي" and possessed("جَدَّةْ") == "جَدَّتِي",
       f"والمضاف إلى ياء المتكلم تُبسَط تاؤه: جَدَّةْ ← {possessed('جَدَّةْ')}")

    # لباس الموضع: يُقاس على **كل جملة في المنظومة** (مثالٍ ومتدرّجة) — فرمزُ فراغها
    # يُعاد بناؤه من كلمة معجمها وثوبِ موضعها حرفاً بحرف، وإلا كذب خيارُ «أكمل».
    sentences_all = [(w["word"], w["sentence"]) for w in data["words"]]
    sentences_all += [(s["word"], s["text"]) for s in (data.get(SENTENCE_FIELD) or [])]
    naked, kinds = [], {}
    for target, text in sentences_all:
        token = blank_token(target, text)
        dress = dress_of(target, token) if token else None
        if not dress or dressed(target, dress) != token:
            naked.append(f"«{target}» ← «{token}» في «{text}»")
            continue
        kinds[dress[0]] = kinds.get(dress[0], 0) + 1
    ok(not naked and sum(kinds.values()) == len(sentences_all),
       f"ولباسُ الموضع يعيد بناء رمز الفراغ في {sum(kinds.values())} جملة "
       f"({'، '.join(f'{k}: {n}' for k, n in sorted(kinds.items()))})"
       + (f" — عارٍ: {naked[:3]}" if naked else ""))
    naked = dressless(data)
    ok(not wearable("أَبِي", ("def", DAMMA), naked)
       and not wearable("أَحْمَرْ", ("poss", ""), naked)
       and wearable("سَرِيرْ", ("def", DAMMA), naked),
       f"ولا يُلبَس ثوباً ثانياً ما أعلنه المعجمُ مفرداً في جملته "
       f"({len(naked)} كلمة: مضافٌ إلى ياء المتكلم أو صفةٌ خبر — «الْأَبِيُ» و«أَحْمَرِي» "
       "ليستا عربيتين)")
    ok(stem(definite("سَرِيرْ", KASRA)) == stem("سَرِيرْ"),
       "وكلُّ مشتقٍّ يعود بجذعه إلى كلمة أساسه (به يعرفه الفاحص)")

    sentences, unknown = build(data)
    owned_texts, _ = build_word_sentences(data)
    # جملُ المثال التي يملكها المولّد مُنتِجةٌ للنصّ كالمتدرّجة، فالمستعمَل مجموعُهما
    used = {stem(w) for entry in sentences for w in entry["text"].split()}
    used |= {stem(w) for text in owned_texts.values() for w in text.split()}
    idle = [t for t in SUPPORT_ADD if stem(t) not in used]
    ok(not idle, f"وكلُّ زيادةٍ في المساند تستعملها جملة ({len(SUPPORT_ADD)} مفردة)"
       + (f" — معطَّل: {idle[:5]}" if idle else ""))

    # حارسُ الأواخر العليلة: لا يقع بعد حرف مدٍّ حركةُ إعرابٍ في شيءٍ مما نولّده
    HARAKAT_ = set(MARKS) - {SUKUN}
    # الغلطُ يقع في **آخر الكلمة** وحدَه: «الْبَطَاطَاُ». وفي وسطها قد يكون الحرفُ
    # نفسُه صحيحاً متحرّكاً لا مدّاً («الْعَالِيَةُ»)، فلا يُقاس عليه.
    ill = [w for txt in [e["text"] for e in sentences] + list(owned_texts.values())
           for w in txt.split()
           if len(w) >= 3 and w[-1] in HARAKAT_ and w[-2] in MADD_BEFORE
           and w[-3] == MADD_BEFORE[w[-2]]]
    ok(not ill, "ولا حركةَ إعرابٍ على منتهٍ بحرف مدّ (المقصور والمنقوص)"
       + (f" — {ill[:3]}" if ill else ""))

    lex = {w["word"] for w in data["words"]}
    off = [t for t, _s in SPECS if t not in lex]
    ok(not off, "وكلُّ هدفٍ كلمةُ معجمٍ لها صورتها" + (f" — خارجه: {off[:5]}" if off else ""))

    ok(not unknown, "وكلُّ رمزٍ في التأليف كلمةُ أساسٍ معلَنة")
    missing = [s for s, (t, _sp) in zip(sentences, SPECS)
               if not {stem(t), stem(t) + "\u0650\u064a"} & {stem(w) for w in s["text"].split()}]
    ok(not missing, "وهدفُ كل جملةٍ حاضرٌ فيها (فراغُ «أكمل» وصورتُه)"
       + (f" — {[m['text'] for m in missing][:3]}" if missing else ""))
    texts = [s["text"] for s in sentences]
    ok(len(set(texts)) == len(texts), "ولا جملة مكرَّرة")

    owned, owned_unknown = build_word_sentences(data)
    ok(not owned_unknown and set(owned) <= lex,
       f"وجملُ المثال التي يملكها المولّد مشتقّةٌ من أصولٍ معلَنة ({len(owned)} جملة)")
    others = [w["sentence"] for w in data["words"] if w["word"] not in WORD_SPECS]
    clash = [f"{w}: {t}" for w, t in owned.items() if t in others or t in texts]
    ok(not clash, "ولا تصادم جملةً أخرى في المنظومة" + (f" — {clash}" if clash else ""))
    ok(all(bare(w) in bare(t) for w, t in owned.items()),
       "وكلمتُها حاضرةٌ فيها")

    print(f"\n{fails} فشل" if fails else "\n✓ المشتقّ والمادّة سليمان")
    return 1 if fails else 0


def main():
    ap = argparse.ArgumentParser(description="مولّد الجمل المتدرجة (الحزمة ٩أ)")
    ap.add_argument("--write", action="store_true", help="كتابة الجمل في ملف المعجم")
    ap.add_argument("--check", action="store_true", help="هل يطابق الملفُّ خرجَ المولّد؟")
    ap.add_argument("--self-test", action="store_true", help="فحص المشتقّ على مادة الحزمة ٧")
    args = ap.parse_args()

    data = load()
    if args.self_test:
        sys.exit(self_test(data))

    sentences, unknown = build(data)
    if args.check:
        want = with_sentences(data, sentences)
        bad = [(w["word"], w["sentence"], WORD_SPECS[w["word"]])
               for w in data.get("words", [])
               if w.get("word") in WORD_SPECS
               and w.get("sentence") != next(x["sentence"] for x in want["words"]
                                             if x["word"] == w["word"])]
        if (data.get(SENTENCE_FIELD) == sentences and not bad
                and (data.get(SUPPORT_FIELD) or []) == want[SUPPORT_FIELD]):
            print(f"✓ {len(sentences)} جملة في المعجم مطابقةٌ لخرج المولّد، "
                  f"و{len(WORD_SPECS)} جملتا مثالٍ يملكهما، والمساند كذلك")
