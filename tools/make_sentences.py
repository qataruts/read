def curriculum_bases():
    """كلمات المنهج بصيغتها المشكولة — يقرؤها من `curriculum.js` لا تُكتب هنا."""
    src = CURRICULUM.read_text(encoding="utf-8")
    _letters, groups, parts = parse_curriculum(src)
    quran = parse_quran(parts.get("QURAN", ""))
    out = {}
    for group in groups:
        for word in group["words"]:
            out["".join(word["tiles"])] = "curriculum"
    for skill in parse_skills(parts.get("SKILLS", "")):
        for text, _emoji in skill["words"]:
            out.setdefault(text, "curriculum")
    for sign in quran["letters"]["signs"]:
        for text, *_ in sign["words"]:
            out.setdefault(text, "curriculum")
    for text, *_ in quran["words"]["items"]:
        out.setdefault(text, "curriculum")
    return out


def all_bases(data):
    """كل ما يجوز أن يرد في التأليف: كلمة معجمٍ، أو كلمة منهجٍ، أو مفردة مساندة."""
    out = curriculum_bases()
    for entry in data.get("words", []):
        out[entry["word"]] = "lexicon"
    for text in data.get("support", []):
        out[text] = "support"
    for text in SUPPORT_ADD:
        out[text] = "support"
    return out


