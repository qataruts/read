SUN = set("تثدذرزسشصضطظلن")      # الحروف الشمسية: تُدغم فيها لام «ال»
FATHA, KASRA, DAMMA = "َ", "ِ", "ُ"
END_MARKS = set(MARKS) | TANWEEN                     # ما يقع آخرَ الكلمة من علامات
CASES = {"n": DAMMA, "i": KASRA, "a": FATHA, "p": SUKUN,
         "u": DAMMA, "k": KASRA, "f": FATHA}
DEFINITE_ROLES = {"n", "i", "a", "p"}


# ————— الاشتقاق: من كلمة الأساس إلى صيغتها في الجملة —————


# حرفُ المدّ وحركتُه المجانسة قبله — بها وحدَها يكون الآخِرُ عليلاً
MADD_BEFORE = {"ا": "َ", "و": "ُ", "ي": "ِ"}


def ill_ended(body):
    """أمنتهٍ بحرف مدٍّ حقيقيّ (مقصورٌ أو منقوص)؟

    **ليس كلُّ ألفٍ أو واوٍ أو ياءٍ في الآخر مدّاً**: «دَلْوْ» و«نَايْ» و«ظَبْيْ» آخرُها
    حرفٌ صحيحٌ ساكن تَظهر عليه الحركة («الدَّلْوُ» و«النَّايُ»). والفارقُ أن حرف المدّ
    تسبقه حركتُه المجانسة وحدَها — وهو عينُ ما يعرفه مقطِّع النورانية في `check_lexicon`.
    """
    if len(body) < 2 or body[-1] not in MADD_BEFORE:
        return False
    before = body[:-1].rstrip(SHADDA)      # «بُنِّي»: الشدّةُ بين الحركة والياء
    return bool(before) and before[-1] == MADD_BEFORE[body[-1]]


def attach(body, mark):
    """إلحاقُ علامة الإعراب — إلا على منتهٍ بحرف مدّ (حكم المدير، ١٠ أغسطس ٢٠٢٦).

    «الْبَطَاطَا» و«الْمُوسِيقَا» و«الْبِيَانُو» و«الْوَادِي» و«الرَّاعِي» والألوانُ
    المنسوبة («الْوَرْدِي») — كلُّها مقصورٌ أو منقوصٌ، ضمّةُ الرفع فيها **مقدَّرة لا
    تُكتَب**. وكتابتُها («الْبَطَاطَاُ») غلطٌ إملائيّ يقرؤه الطفل حرفاً بحرف.
    """
    return body if ill_ended(body) else body + mark


def strip_end(word):
    """نزع علامة الآخر (سكون الوقف أو حركة أو تنوين) — وما عداها يبقى."""
    return word[:-1] if word and word[-1] in END_MARKS else word


def definite(base, mark):
    """«الـ» + الكلمة + علامة الآخر، بالإدغام الشمسي كما تُكتب في المصادر.

    قمريّ: «الْ» ساكنة اللام («الْغُرْفَةُ»). وشمسيّ: لام بلا حركة وشدّةٌ على الحرف
    بعد حركته («السَّرِيرُ») — وهو عين ما يقبله فاحص المفكوكية بعد درس اللام الشمسية.
    """
    body = strip_end(base)
    if not body:
        raise ValueError("كلمة فارغة")
    if body[0] in SUN:
        return attach("ال" + body[0] + body[1] + SHADDA + body[2:], mark)
    return attach("ال" + SUKUN + body, mark)


def raised(base):
    """فعلٌ مضارع مرفوع داخل الجملة: سكونُ الوقف يصير ضمّة، والمعتلّ الآخر يبقى."""
    if base and base[-1] == SUKUN:
        return base[:-1] + DAMMA
    return base            # «يَمْشِي» و«تَقْطَعُ»: لا يظهر عليهما التغيير


def possessed(base):
    """المضاف إلى ياء المتكلم: «أُذُنْ» ← «أُذُنِي»، والتاء المربوطة تُبسَط تاءً
    («جَدَّةْ» ← «جَدَّتِي») — وهي صيغةُ عشر جملٍ في المادّة المعتمدة."""
    body = strip_end(base)
    return (body[:-1] + "ت" if body.endswith("ة") else body) + KASRA + "ي"


# ————— لباس الموضع: به تُلبَس مشتّتاتُ «أكمل الجملة» ثوبَ الهدف —————
#
# خيار «أكمل» يُعرض **بالرمز الذي سيملأ الفراغ** (حكم المدير، ٦ أغسطس ٢٠٢٦)، فيلزم
# أن يلبس المشتّتان ثوبَ الهدف نفسَه. والثوب لا يُكتب في بياناتٍ ولا يُخمَّن: يُستنبَط
# **بالمقايسة** — أيُّ اشتقاقٍ من هذه الأربعة يعيد بناء رمز الفراغ حرفاً بحرف.
# ونظيرُها في التطبيق `dressOf`/`dressed` في `app/js/sentences.js`.

DRESSES = {
    "none": lambda base, mark: base,                    # آخرُ الجملة موقوفاً كما في المعجم
    "def": definite,                                    # «الـ» وعلامة الموضع
    "bare": lambda base, mark: attach(strip_end(base), mark),   # نكرةٌ بعلامة الموضع
    "poss": lambda base, mark: possessed(base),         # مضافٌ إلى ياء المتكلم
}


def dress_of(base, token):
    """ثوبُ الموضع (النوع، علامة الآخر) — أو `None` إن عجزت الأربعة عن بنائه.

    والمنقوصُ والمقصور لا تظهر عليهما الحركة («الرَّاعِي»)، فرمزُ فراغهما بلا علامةِ
    آخرٍ يُقرأ منها الموضع. ولو أُخذ ذلك على ظاهره لَلبِس المشتّتُ ثوباً بلا حركة
    («الْجَدَّة») وهو غلط — فتُجرَّب على المنتهي بمدٍّ **حركاتُ الإعراب أوّلاً**،
    والضمّةُ أولاها (موضعُ الهدف في مادّتنا مبتدأٌ مرفوع)، ثم يُقاس عليها المشتّت.
    """
    mark = token[-1] if token and token[-1] in END_MARKS else ""
    marks = [mark] if mark else ([DAMMA, KASRA, FATHA, ""] if ill_ended(strip_end(base)) else [""])
    for candidate in marks:
        for kind, wear in DRESSES.items():
            try:
                if wear(base, candidate) == token:
                    return kind, candidate
            except (IndexError, ValueError):
                continue
    return None


def dressed(base, dress):
    """كلمةُ معجمٍ ← صيغتُها في ذلك الموضع."""
    return DRESSES[dress[0]](base, dress[1]) if dress else base


def dressless(data):
    """كلماتُ المعجم التي **لا تلبس ثوباً**، والمعجمُ هو الذي يعلنها لا تخمينُ صرفٍ:
    الكلمة التي تظهر في **جملتها هي** بصيغتها المفردة إمّا مضافةٌ إلى ياء المتكلم
    («أَبِي كَرِيمْ») أو صفةٌ خبر («الْبَحْرُ أَزْرَقْ») — وكلتاهما لا تُعرَّف ولا تُضاف
    («الْأَبِيُ» و«أَحْمَرِي» ليستا عربيتين). (نظيرتها `DRESSLESS` في `sentences.js`.)
    """
    out = set()
    for entry in data.get("words", []):
        token = blank_token(entry.get("word", ""), entry.get("sentence", ""))
        dress = dress_of(entry["word"], token) if token else None
        if not dress or dress[0] == "none":
            out.add(entry["word"])
    return out


def wearable(base, dress, naked=frozenset()):
    """هل تقبل هذه الكلمةُ لباسَ الموضع؟ (`naked` = خرجُ `dressless`)"""
    return not dress or dress[0] == "none" or base not in naked


def blank_token(target, text):
    """رمزُ الفراغ: كلمةُ الهدف في جملتها. تُطابَق بجذعها، وإلا فبما بُني عليه
    («أُخْتْ» ← «أُخْتِي») — نظيرةُ `blankIndex` في `app/js/sentences.js`."""
    words = str(text or "").split()
    root = stem(target)
    for word in words:
        if stem(word) == root:
            return word
    for word in words:
        if stem(word).startswith(root):
            return word
    return ""


def render(token, bases):
    """رمزُ المؤلِّف ← صيغتُه في الجملة. يرفض أي كلمة أساسٍ غير معلَنة."""
    base, _, role = token.partition("~")
    if base not in bases:
        raise KeyError(base)
    if not role:
        return base
    if role == "v":
        return raised(base)
    if role == "m":                       # مضافٌ إلى ياء المتكلم: «أُذُنْ» ← «أُذُنِي»
        return possessed(base)
    if role not in CASES:
        raise ValueError(f"دورٌ مجهول «{role}» في «{token}»")
    if role in DEFINITE_ROLES:
        return definite(base, CASES[role])
    return attach(strip_end(base), CASES[role])


