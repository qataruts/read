def render_token(token: str, bases: dict, *, title: bool = False) -> str:
    """رمزٌ ← صيغتُه. الأدوارُ أدوارُ ٩أ، وزيادةً `~N` تنوينُ الضمّ لاسم العلم.

    وسابقةُ `+` عطفٌ بواوٍ ملتصقة — **في العنوان وحده** (الاستثناء المعلَن أعلاه).
    """
    if token.startswith("+"):
        if not title:
            raise ValueError(f"واوُ العطف الملتصقة في غير عنوان: «{token}» — "
                             "الملتصقُ ممنوعٌ في المتون (قاعدة ٩أ)")
        return WAW + render_token(token[1:], bases, title=title)
    base, _, role = token.partition("~")
    if role in TANWIN_ROLES:
        if base == LAFZ_JALALA:
            raise ValueError("لفظُ الجلالة معرفةٌ لا يُنوَّن — «اللَّٰهٌ» ممتنعٌ نحواً وشرعاً "
                             f"(الدور «~{role}»); استعمل `~u`")
        if base not in bases:
            raise KeyError(base)
        return strip_end(base) + TANWIN_ROLES[role]
    return render(token, bases)


def compose(spec: str, bases: dict, unknown: list, *, title: bool = False) -> str:
    """رموزٌ ← جملةٌ مشكولة. الرمزُ الذي لا أصلَ له يُسجَّل ويُترك كما هو."""
    words = []
    for token in spec.split():
        try:
            words.append(render_token(token, bases, title=title))
        except KeyError as e:
            unknown.append((str(e.args[0]), spec))
            words.append(token)
    return " ".join(words)


def all_bases(data: dict) -> dict:
    """كل ما يجوز أن يرد في التأليف: أصول ٩أ + معاجم المكتبة والقرآنية والرفّ."""
    out = sentence_bases(data)
    for text in LIBRARY_SUPPORT:
        out[text] = "library"
    for text in QURAN_SUPPORT:
        out[text] = "quran"
    for text in SHELF_SUPPORT:
        out[text] = "shelf"
    return out


def build(data: dict) -> tuple:
    """من الرموز إلى قصصٍ مشكولة — وأي كلمة أساسٍ غير معلَنة توقف البناء."""
    bases = all_bases(data)
    unknown = []
    out = []
    for spec in SPECS:
        # **مقاطعُ الأسئلة يملكها الفاحص** كما تملك حدودَ المستوى: المؤلِّف يكتب
        # الأسئلة بترتيبها، و`segments_of` تُلبسها مواضعَها — فلو تغيّر طولُ القصة
        # تحرّك عددُها وحدَه، ولا رقمَ يُكتب بيد.
        pages = spec["pages"]
        marks = segments_of(len(pages)) if spec.get("shelf") else [len(pages)]
        asks = spec["asks"] if "asks" in spec else [spec["ask"]]
        if len(asks) != len(marks):
            raise ValueError(f"«{spec['id']}»: {len(asks)} سؤالاً و{len(marks)} مقطعاً "
                             f"({len(pages)} صفحة ⇐ {marks}) — سؤالٌ لكل مقطع")
        story = {
            "id": spec["id"],
            "level": spec["level"],
            # محاورُ الموضع ثلاثة: بستانٌ للمكتبة، وسورةٌ للقرآنية، ورفٌّ للطويلة.
            "garden": spec.get("garden", ""),
            "surah": spec.get("surah", ""),
            "shelf": spec.get("shelf", ""),
            "title": compose(spec["title"], bases, unknown, title=True),
            "emoji": spec["emoji"],
            "pages": [{"text": compose(text, bases, unknown), "emoji": emoji}
                      for text, emoji in pages],
            "questions": [{
                "upto": upto,
                "text": compose(ask[0], bases, unknown),
                "answer": ask[1],
                "distractors": list(ask[2]),
            } for upto, ask in zip(marks, asks)],
        }
        out.append({key: story[key] for key in STORY_FIELDS})
    return out, unknown


def story_texts(story: dict) -> list:
    """كلُّ نصٍّ مؤلَّفٍ في قصة: عنوانُها وصفحاتُها وأسئلةُ مقاطعها."""
    return [story["title"], *(p["text"] for p in story["pages"]),
            *(a["text"] for a in story["questions"])]


def library_support(stories: list) -> list:
    """المعلَن بعد طرح ما لا تستعمله قصة (لا معجم ميت — كما في مساند ٩أ).

    والقوائمُ الثلاث تُعلَن في حقلٍ واحد لأنّ الفاحص يقرأ حقلاً واحداً — وتفريقُها في
    الشيفرة لا في الملف: `LIBRARY_SUPPORT` لقصص البساتين، و`QURAN_SUPPORT` لقصة السورة،
    و`SHELF_SUPPORT` لرفّ المكتبة. والميزانياتُ ثلاثٌ لأنّ المواضع ثلاثة.
    """
    used = {stem(word) for story in stories
            for text in story_texts(story) for word in text.split()}
    return [text for text in [*LIBRARY_SUPPORT, *QURAN_SUPPORT, *SHELF_SUPPORT]
            if stem(text) in used]


def index_of(stories: list) -> dict:
    return {
        "version": 1,
        "note": "مكتبة «مصنع القصص» (الحزمة ٩) — تُؤلَّف بـtools/make_stories.py "
                "ويفحصها tools/check_lexicon.py، ولا تُحرَّر بيد.",
        SUPPORT_FIELD: library_support(stories),
        "stories": [story["id"] for story in stories],
    }


def dump_index(index: dict) -> str:
    return json.dumps(index, ensure_ascii=False, indent=2) + "\n"


def write(stories: list) -> None:
    STORIES_DIR.mkdir(parents=True, exist_ok=True)
    for story in stories:
        (STORIES_DIR / f"{story['id']}.json").write_text(dump_story(story), encoding="utf-8")
    STORY_INDEX.write_text(dump_index(index_of(stories)), encoding="utf-8")
    keep = {f"{story['id']}.json" for story in stories} | {"index.json"}
    for path in STORIES_DIR.glob("*.json"):
        if path.name not in keep:
            path.unlink()


def report(stories: list, unknown: list) -> int:
    by_level = {}
    for story in stories:
        by_level[story["level"]] = by_level.get(story["level"], 0) + 1
    pages = sum(len(s["pages"]) for s in stories)
    print(f"القصص المؤلَّفة: {len(stories)} في {pages} صفحة | "
          + "، ".join(f"مستوى {lv}: {n}" for lv, n in sorted(by_level.items()))
          + f" | معجم المكتبة: {len(library_support(stories))} مفردة")
    if unknown:
        print(f"\nكلماتُ أساسٍ غير معلَنة ({len(set(u for u, _ in unknown))}):")
        for base in sorted({u for u, _ in unknown}):
            print(f"  ✗ {base}")
        return 1
    return 0


