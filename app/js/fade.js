// خفوت التشكيل المتدرّج — حزمة «الخفوت» ز١→ز٣ (ROADMAP §المرحلة ز).
//
// **العلّة**: التشكيل ضروريّ للمبتدئ عبءٌ على المتقدّم. والكتب والصحف التي سيقرؤها
// طفلنا يوماً بلا شكل، فإن بقي التطبيق يشكّل له كلَّ حرفٍ إلى الأبد صنعنا قارئاً
// لا يقرأ إلا عندنا. والجسرُ أن **يخفت الشكل عن كل كلمةٍ وحدها بحسب تاريخ الطفل معها**
// — لا خفوتٌ جماعيّ اعتباطيّ بيومٍ أو بمرحلة.
//
// ثلاث درجات، كلٌّ منها عتبةٌ في عدّاد قراءات الكلمة الصحيحة المتباعدة (`progress.js`):
//   ز١ — **كامل الشكل** دون العتبة (وهي حالُ كل كلمةٍ يلقاها الطفل أوّل مرّة).
//   ز٢ — **الهيكل مع علامات المفاتيح**: تبقى الشدّة والتنوين والمدود (الألف الخنجرية
//        والمدّة)، وتخفت الحركات القصيرة والسكون. وهي عين الكتابة العربية المشكولة
//        جزئياً في كتب الناشئة — لا اختراعَ لنا فيها.
//   ز٣ — **عارٍ تماماً** عند ضِعف العتبة: رسمُ الصحيفة والكتاب.
//
// و**الشكل عند الطلب**: في ز٢ وز٣ نقرةٌ على الكلمة تكشف شكلها كاملاً ثوانيَ ثم تعود —
// فلا يقف الطفل أمام كلمةٍ عجز عنها، ولا يُحرم من الشكل من يحتاجه. والكشفُ **تراجعٌ
// جزئيّ** في عدّادها (`revealRead`): من احتاج شكلَ كلمةٍ لم ينضج بعدُ لعريها.
//
// **أين يسري**: النصّ المتّصل الذي يقرؤه الطفل — سطورُ القصص، وجملُ السلّم وسؤالِ
// الفهم، وبطاقاتُ كلمات البساتين. وأين **لا يسري**:
//   • **مواد التهجّي** (المقاطع، دروس الحروف والمهارات، لعبة الكلمات، المراجعة):
//     الشكل هناك **مادّةُ الدرس لا كسوتَه** — كلمةٌ بلا حركاتها لا تُتهجّى أصلاً.
//   • **نصّ المصحف**: رسمُه مقدَّس كما هو، لا يُنقص منه حرفٌ ولا حركة.
//   • **حوضُ الخيارات** في كل تمرين (بلاطات «رتّب»، وخيارات «أكمل» و«اقرأ واختر»):
//     لو خفتت كلمةٌ وبقيت أختُها مشكولةً لصار **فرقُ التشكيل دليلاً على الجواب** —
//     يُجيب الطفل بعدّ الحركات لا بالقراءة. فالحوضُ كلُّه بدرجةٍ واحدة: ز١.
//
// **ولا يغيّر الخفوتُ قياساً**: العدّاد يرتفع بمواضع «الشاهد الواحد» (أدناه)، والقياس
// (ليتنر) يقع على الكلمة نفسها بصيغتها الكاملة كما كان — الخفوتُ كسوةٌ لا مادّة.
//
// حارساه: `tools/test_fade.mjs` (القاعدة والمصدر) و`browser_test.py --fade` (الشاشة).

import * as progress from './progress.js';
import { holdFade } from './support.js';
import { h } from './ui.js';

/** العتبة: ثلاث قراءات صحيحة **متباعدة** — ثابتٌ معلَن قابل للمعايرة. */
export const FADE_AT = 3;

/** ضِعف العتبة: عندها يتعرّى رسمُ الكلمة تماماً. */
export const BARE_AT = FADE_AT * 2;

/** كم يبقى الشكل مكشوفاً بعد النقر — ثوانٍ تكفي لقراءةٍ متأنّية ثم يعود. */
export const REVEAL_MS = 3000;

// علامات التشكيل بمجموعاتها. المدود هنا علامتان لا حروف: الألفُ الخنجرية «ٰ»
// والمدّة «ٓ» — أمّا ألفُ المدّ وواوُه وياؤه فحروفٌ لا تُمسّ في درجةٍ من الدرجات.
const SHORT = /[\u064E-\u0650\u0652]/g;       // فتحة وضمة وكسرة وسكون — ما يخفت في ز٢
const ALL_MARKS = /[\u064B-\u0653\u0670]/g;   // التشكيل كلّه (بشدّته وتنوينه ومدوده)

/** درجةُ عرضِ كلمةٍ من عدد قراءاتها: ١ كامل الشكل، ٢ هيكلٌ بمفاتيحه، ٣ عارٍ. */
export function levelOf(count) {
  if (count >= BARE_AT) return 3;
  return count >= FADE_AT ? 2 : 1;
}

/**
 * درجةُ هذه الكلمة الآن بتاريخ الطفل معها.
 *
 * **ومِقبضُ «التشكيل الثابت»** (وضعُ الدعم، الجلسة د١ — حاجةُ عُسر القراءة بعينها):
 * يمسك الدرجةَ عند ز١ فيبقى الشكلُ كاملاً حتى يقرّر الوالدُ رفعَه. وهو **عرضٌ لا
 * قياس**: `levelOf` تبقى دالّةً نقيّة، و**عدّادُ القراءات لا يُمَسّ ببايت** — يمضي
 * كما كان، فيومَ يُطفَأ المفتاح تجد الكلماتُ درجاتِها التي بلغتها في غيابه.
 */
export const wordLevel = (text) =>
  (holdFade() ? 1 : levelOf(progress.readCount(progress.wordKey(text))));

/**
 * صورةُ الكلمة في درجتها. **لا يُحذف حرفٌ أبداً** — علاماتٌ تُنزع لا غير،
 * فالمفكوكية باقيةٌ بعينها ويثبته الحارس بمقايسة حروف الصورتين.
 */
export function fadeText(text, level) {
  const out = String(text ?? '');
  if (level >= 3) return out.replace(ALL_MARKS, '');
  if (level === 2) return out.replace(SHORT, '');
  return out;
}

/** الكلمة كما تُعرض للطفل الآن (الصورةُ الافتراضية في مواضع الخفوت الثلاثة). */
export const faded = (text) => fadeText(text, wordLevel(text));

// ————— «قاعدة الشاهد الواحد» (حزمة «قياس العلامات» — تقسية إشارة العدّاد) —————
//
// **العلّة** (مرفوعُ المراجعة الخارجية البرتقاليّ، ١١ أغسطس ٢٠٢٦): كان الاحتساب يقع
// من خمسة مواضع، ثلاثةٌ منها تُحتسب **الجملةَ كلها** (٣–٥ كلمات) من نقرةٍ بين ثلاث
// صور — احتمالُها الثلث. فطفلٌ يخمّن ثلاثَ مرّات موفَّقة في ثلاثة أيام يبلغ بكلماته
// عتبةَ الخفوت بلا أن يقرأ حرفاً. والإشارةُ التي تُشترى بالتخمين لا تُبنى عليها
// درجة عرضٍ تلاحق الطفل في كل شاشة.
//
// **القاعدة** (قرار المدير في الجلسة): لا تُحتسب قراءةُ كلمةٍ إلا من موضعٍ شهد
// **لتلك الكلمة وحدَها**:
//   • «رتّب» — الكلمةُ المطلوبة في موضعها (شاهدٌ لكلمةٍ بعينها، كما يُقاس ليتنر).
//   • «أكمل» — الكلمةُ التي ملأت الفراغ وحدَها لا الجملةُ كلها (وخياراتُها ملبَّسةٌ
//     بلباس الموضع، فلا يُميَّز الجواب إلا بقراءته).
//   • «اقرأ واختر» في البستان — الكلمةُ المختارة من ثلاثٍ **مكتوبة**.
// وسقط الاحتساب من «اقرأ ونفّذ» وسؤالِ الفهم: شاهدُهما جملةٌ لا كلمة.
//
// و**القاعدة بنيوية لا وصيّة**: هذه الدالّة تقبل **كلمةً واحدة** لا قائمة، فاحتسابُ
// جملةٍ كاملةٍ من نقرةٍ واحدة صار مستحيلاً لا ممنوعاً. يحرسه `tools/test_fade.mjs`.

/**
 * احتساب قراءةٍ صحيحة **لكلمةٍ واحدة** — مدخل العدّاد الوحيد من الشاشات.
 * ما ليس نصّاً مفرداً يُردّ صامتاً (قائمةٌ مرَّت سهواً لا تُحتسب كلماتُها).
 * @returns {boolean} هل ارتفع العدّاد فعلاً؟ (التباعدُ يفرضه `progress.js`)
 */
export function credit(text) {
  if (!text || typeof text !== 'string') return false;
  return progress.recordRead(text);
}

// ————— «الشكل عند الطلب» —————

/**
 * إلباسُ عنصرٍ كلمةً بدرجة خفوتها، ونصبُ الكشف عند الطلب على مضيفه.
 *
 * `el` هو صندوق الحبر (تتبدّل فيه الصورة)، و`host` هدفُ اللمس (قد يكون أباه —
 * بطاقةُ البستان مثلاً: الصورةُ والكلمةُ زرٌّ واحد). ويعلن العنصرُ كلمتَه ودرجتَها
 * في `data-word` و`data-fade`: كان النصُّ يُقرأ من الشاشة كما هو فصار صورةً له،
 * فلولا الإعلان لعميت عنه الاختباراتُ التي تتحقّق أن المعروض هو المقصود.
 */
export function fadeWord(el, text, host = el) {
  const paint = () => {
    const level = wordLevel(text);
    el.textContent = fadeText(text, level);
    el.dataset.fade = String(level);        // الإعلان على صندوق الحبر لا على مضيفه
  };
  el.dataset.word = text;
  paint();

  host.addEventListener('click', () => {
    if (wordLevel(text) === 1) return;      // مشكولةٌ أصلاً: لا كشفَ ولا تراجع
    // ونقرةٌ على مكشوفةٍ لا تُحتسب: نقراتُ الطفل المتتابعة على كلمةٍ واحدة **طلبٌ
    // واحد** لا أربعة — وإلا هوت الكلمة من ز٣ إلى ز١ بضربةِ إصبعٍ مرتبكة.
    if (el.classList.contains('word--shown')) return;
    el.textContent = text;
    el.classList.add('word--shown');
    progress.revealRead(text);              // كشفُ الشكل تراجعٌ جزئيّ في عدّادها
    setTimeout(() => {
      if (!el.isConnected) return;
      el.classList.remove('word--shown');
      paint();                              // بدرجتها **بعد** التراجع — قد تعود إلى ز١
    }, REVEAL_MS);
  });
  return host;
}

/**
 * كلمةٌ في نصٍّ متّصل (سطرُ قصة، جملةُ سلّمٍ أو سؤال). المشكولةُ تبقى عنصراً صامتاً
 * كما كانت، والمخفوتةُ تصير زرّاً — فما لا يُكشف لا يُغرى بلمسه.
 */
export function textWord(text, { className = '', tag = 'span', label, onclick } = {}) {
  const faded = wordLevel(text) > 1;
  const el = h(faded || onclick ? 'button' : tag, {
    class: className,
    'aria-label': label ?? (faded ? text : null),
    onclick,
  });
  fadeWord(el, text);
  return el;
}
