/** هل وضعُ الدعم كلُّه مشتغل؟ (المفتاح الأعلى — وهو مطفأٌ ابتداءً). */
export const modeOn = () => state.on === true;

/**
 * هل هذا المقبض مشتغل؟ — **المقابض تتبع المفتاح الأعلى** ابتداءً: يشغّل وليُّ الأمر
 * الوضعَ فتعمل كلُّها، ثم يطفئ ما لا يحتاجه طفلُه (فالتشغيل قرارٌ واحد لا سبعة).
 */
export const isOn = (key) => modeOn() && key in KNOBS && state[key] !== false;

/** مقدارُ هذا المقبض الآن — `standing` ما دام مطفأً، و`supported` إن اشتغل. */
export const value = (key) => (isOn(key) ? KNOBS[key].supported : KNOBS[key].standing);

/** جرعةُ جلسة المراجعة (تمارين). */
export const sessionSize = () => value('dose');

/** عددُ المشتّتات في تمرين اختيار (والخياراتُ = هدفٌ + مشتّتاته). */
export const distractors = () => value('pool');

/** أيّامُ صندوق ليتنر بعد تقاربها — والصفرُ يبقى صفراً (اليومُ نفسُه). */
export const days = (d) => (d ? Math.max(1, Math.round(d * value('spacing'))) : 0);

/** الهدوءُ الحسّي: يشغّله صنفٌ على الجذر يستدعي قواعدَ خفض الحركة القائمة. */
export const calm = () => value('calm') === true;

/** تجميدُ الخفوت عند ز١ — عرضاً فقط: عدّادُ القراءات لا يُمسّ. */
export const holdFade = () => value('hold') === true;

/** سرعةُ تشغيل ملفّ الصوت (١ = كما هو — فلا يُمَسّ العنصرُ أصلاً). */
export const rate = () => value('pace');

/**
 * **التلقين في الاكتساب وحدَه** (حكمُ الدراسة ٣/أ — تحديدُ نطاقٍ لا نقضُ قاعدة):
 * التعلّمُ بلا خطأ مصمَّمٌ لمرحلة الاكتساب، و«لا تلقين للصواب» قاعدةُ الطلاقة
 * (Haring 1978: اكتساب ← طلاقة ← تعميم ← تكييف). فالتلميحُ لا يجوز إلا في
 * **أوّل لقاءٍ بعنصرٍ جديد**: صندوقُ ليتنر صفر — وما ارتفع صندوقُه فقد جاوز الاكتساب.
 *
 * وهي **إذنٌ لا فعل**: من يعرضه شاشةُ اكتسابٍ تستدعيها، ولا تستدعيها المراجعةُ ولا
 * البوابتان ولا اللحاق ألبتّة — وحصانتُها بنيوية: تلك الوحداتُ لا تعرف هذه الدالّة
 * أصلاً، يجردها `tools/test_support.mjs` على المصدر.
 */
export const mayPrompt = (box) => value('prompt') === true && box === 0;

// ————— الكتابة: من لوحة وليّ الأمر وحدَها —————

/** تشغيلُ الوضع كلِّه أو إطفاؤه (والإطفاء يردّ السلوكَ القائم بلا فقد اختياراته). */
export function setMode(on) {
  state = { ...state, on: on === true };
  save();
}

/** تشغيل مقبضٍ بعينه أو إطفاؤه — والمشتغلُ هو الأصل فلا يُخزَّن إلا المطفأ. */
export function set(key, on) {
  if (!(key in KNOBS)) return;
  const next = { ...state };
  if (on === false) next[key] = false;
  else delete next[key];
  state = next;
  save();
}

/** لإعادة المخزن إلى فراغه (الاختبارات، وزرُّ «أعِد الافتراضات» في اللوحة). */
export function reset() {
  state = {};
  save();
}
