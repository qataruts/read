/**
 * **التلقين في الاكتساب وحدَه** (حكمُ الدراسة ٣/أ — تحديدُ نطاقٍ لا نقضُ قاعدة):
 * التعلّمُ بلا خطأ مصمَّمٌ لمرحلة الاكتساب، و«لا تلقين للصواب» قاعدةُ الطلاقة
 * (Haring 1978: اكتساب ← طلاقة ← تعميم ← تكييف). فالتلميحُ لا يجوز إلا في
 * **أوّل لقاءٍ بعنصرٍ جديد**: صندوقُ ليتنر صفر — وما ارتفع صندوقُه فقد جاوز الاكتساب.
 *
 * وهي **إذنٌ لا فعل**: من يعرضه شاشاتُ الاكتساب الأربع (`lesson.js` · `words.js` ·
 * `skill.js` · `garden.js`)، ولا تستدعيها المراجعةُ ولا البوابتان ولا اللحاق ألبتّة
 * — وحصانتُها بنيوية: تلك الوحداتُ لا تعرف هذه الدالّة أصلاً، يجردها
 * `tools/test_support.mjs` على المصدر. **وطبقةٌ ثانية في الامتحان**: `prompt` من
 * `measures` فيعود إلى `standing` داخل `duringExam` ولو استدعاه مستدعٍ يوماً.
 */
export const mayPrompt = (box) => value('prompt') === true && box === 0;

