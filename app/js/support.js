/** هل وضعُ الدعم كلُّه مشتغل؟ (المفتاح الأعلى — وهو مطفأٌ ابتداءً). */
export const modeOn = () => state.on === true;

/**
 * هل هذا المقبض مشتغل؟ — **المقابض تتبع المفتاح الأعلى** ابتداءً: يشغّل وليُّ الأمر
 * الوضعَ فتعمل كلُّها، ثم يطفئ ما لا يحتاجه طفلُه (فالتشغيل قرارٌ واحد لا سبعة).
 */
export const isOn = (key) => modeOn() && key in KNOBS && state[key] !== false;

// ————— «مسطرةُ الامتحان الواحدة» (بلاغ `2026-08-17-support-and-placement-coexist.md`) —————
//
// **قاعدةُ المالك**: العونُ الذي **يريح** يُسمح في امتحان اللحاق، والذي **يجيب**
// يُمنع. فداخل الامتحان تُعطَّل مقابضُ `measures` قطعاً (جرعةٌ وحوضٌ وتلقين) وتسري
// مقابضُ الراحة (صوتٌ أبطأ وهدوءٌ حسّيّ وتشكيلٌ ثابت) — فيُقاس الطفلُ بمسطرةٍ
// واحدة ولا يُمتحَن بشاشةٍ تُربكه، ولا يُفتَح له بحوضٍ أضيق ما لم يُفتَح لغيره.
//
// **ونطاقُه مدّةُ البناء لا عَلَمٌ يُخزَّن**: `duringExam` تلفّ نداءً **متزامناً**
// وتردّ الحالَ في `finally` — فلا يبقى الامتحانُ مشتغلاً بعد مغادرة الطفل شاشتَه،
// ولا يعبر إعادةَ تحميل. وهو يكفي بالبناء: مقاديرُ الصعوبة كلُّها تُقرأ **لحظةَ
// بناء التمارين** (`buildSession` وحدَها تقرأ الجرعةَ والحوض، والتلقينُ لا تعرفه
// شاشاتُ الامتحان أصلاً)، أمّا ما يُقرأ عند الإجابة — موعدُ ليتنر — فمقبضُ راحةٍ
// يسري كما يسري خارجَه: امتحانُ موضعٍ لا يقطع إيقاعَ مراجعة الطفل.
let examDepth = 0;

/** هل نحن الآنَ داخل بناءِ امتحانِ لحاق؟ */
export const examOn = () => examDepth > 0;

/** يُجري `fn` بمسطرة الامتحان الواحدة ويردّ الحالَ ولو رمى (نداءٌ متزامن). */
export function duringExam(fn) {
  examDepth++;
  try {
    return fn();
  } finally {
    examDepth--;
  }
}

/**
 * مقدارُ هذا المقبض الآن — `standing` ما دام مطفأً، و`supported` إن اشتغل.
 * **وداخل الامتحان يعود كلُّ ما يمسّ القياس إلى `standing`** ولو كان مشتغلاً.
 */
export const value = (key) => (
  isOn(key) && !(examOn() && KNOBS[key].measures) ? KNOBS[key].supported : KNOBS[key].standing);

