// ————— كلمات السورة (الحزمة ١٢ «الجسر القرآني») —————
//
// **لا تُكتب كلمةٌ منها بيد أحد**: هي عينُ كلمات آيات السورة مشقوقةً عند الفراغ،
// فمصدرُها مصدرُ الآية نفسه (مشروع تنزيل عبر `tools/quran_source.txt`)، وأيُّ زيادة
// أو نقص فيها يكشفها الفاحص بالمطابقة الحرفية. ولكل كلمة موضعُها (آيةٌ ورقمٌ فيها)
// — به تُجلب تلاوتُها كلمةً-كلمة، وبه تُبنى جولةُ «جِدْها في الآية».
// والمكرَّرُ يُطوى إلى أول موضعٍ ورد فيه: بطاقةٌ واحدة للكلمة الواحدة.

/** وجه محطة كلمات السورة — زخرفة المصحف لا إيموجي (DESIGN §٦: لا إيموجي في شاشات السور). */
export const SURAH_WORDS_FACE = '۞';

/** جزءُ محطةِ كلماتِ سورةٍ من معرّف عقدتها (`sw-s1`) — بادئةٌ لا تلتبس بـ`words1`. */
export const surahWordsPart = (surahId) => `sw-${surahId}`;

/** السورةُ التي تخصّها محطةُ كلماتٍ، أو null إن لم يكن الجزءُ محطةَ كلمات. */
export const surahOfWordsPart = (part) =>
  (String(part).startsWith('sw-') ? surahById(String(part).slice(3)) : null);

/** كلمات السورة بترتيب ورودها، بلا تكرار، ومع موضع أول ورودٍ لكل كلمة. */
export function surahWords(surah) {
  const out = new Map();
  surah.ayat.forEach((ayah, i) => {
    ayah.split(' ').forEach((text, j) => {
      if (text && !out.has(text)) out.set(text, { text, ayah: i + 1, pos: j + 1 });
    });
  });
  return [...out.values()];
}

/**
 * عقد المرحلة القرآنية بالترتيب: الحرفان ← ثلاث درجات كلمات ← الرسم ← المقطَّعة ←
 * (كلماتُ السورة ← السورة) × أربع.
 * **وموضعُ محطة الكلمات قبل سورتها مباشرةً هو قفلُ السورة**: القفل في الرحلة تسلسليّ،
 * فلا تُفتح سورةٌ حتى تُتمّ كلماتُها (يحرسه `test_quran.mjs` على ترتيب العقد نفسِه).
 */
export function quranParts() {
  return [
    { part: QURAN.letters.id, title: QURAN.letters.title, face: QURAN.letters.face },
    ...QURAN.words.levels.map((l) => ({ part: l.id, title: l.title, face: l.face })),
    ...[QURAN.rasm, QURAN.muqattaat]
      .map((part) => ({ part: part.id, title: part.title, face: part.face })),
    ...QURAN.surahs.flatMap((s) => [
      { part: surahWordsPart(s.id), title: `كلمات سورة ${s.name}`, face: SURAH_WORDS_FACE },
      { part: s.id, title: `سورة ${s.name}`, face: s.emoji },
    ]),
  ];
}

export const surahById = (id) => QURAN.surahs.find((s) => s.id === id) || null;

/** درجةٌ من درجات «كلمات من القرآن» بمعرّفها. */
export const quranWordLevel = (id) => QURAN.words.levels.find((l) => l.id === id) || null;

/** كلمات المرحلة الإملائية كلها (الدرجات الثلاث مجموعةً) — لمن يريد الحوض لا الدرجة. */
export const quranWordItems = () => QURAN.words.levels.flatMap((l) => l.items);

/**
 * نصوص المرحلة القرآنية **المولَّدة**: كلامنا نحن (القواعد) وكلمات إملائية وأسماء حروف.
 * لا نصّ من المصحف فيها البتّة — تلاوته من تسجيل قارئ متقن (METHOD §٥.٦).
 */
export function quranSpokenTexts() {
  return [
    QURAN.letters.rule,
    ...QURAN.letters.signs.flatMap((s) => s.words.map((w) => w.read)),
    QURAN.words.rule,
    ...quranWordItems().map((w) => w.read),
    QURAN.rasm.rule,
    ...QURAN.rasm.signs.map((s) => s.rule),
    QURAN.muqattaat.rule,
    ...QURAN.muqattaat.items.flatMap((m) => m.parts.map((p) => p.say)),
  ];
}

/**
 * نصوص المصحف المعروضة للقراءة — **يحرم توليدُ صوتها آلياً** (METHOD §٥.٦): لا
 * مولّد ولا نطقاً آلياً بالمتصفّح. تلاوتها من تسجيل قارئ متقن جائزةٌ ومطلوبة،
 * ومسارها `recitation.js` وحده (ملفٌ بمفتاح نصّه، وبيانٌ مستقلّ عن فهرس المولَّد).
 * وهذه القائمة هي ما يفحصه الحرّاس: نصٌّ منها في فهرس الأصوات المولّدة أو في قائمة
 * الانتظار أو مارٌّ على `audio.play()` — إخفاقٌ صريح.
 */
export function quranMushafTexts() {
  return [
    QURAN.basmala,
    ...QURAN.rasm.signs.map((s) => s.read),
    ...QURAN.muqattaat.items.map((m) => m.read),
    ...QURAN.surahs.flatMap((s) => s.ayat),
  ];
}

/**
 * كلمات محطات السور مفردةً (الحزمة ١٢) — نصُّ مصحفٍ يُتلى بصوت قارئ ولا يُولَّد.
 *
 * **ولِمَ قائمةٌ ثانية لا ذيلٌ لسابقتها؟** لأنّ الكلمة المفردة قد تكون **حرفياً** كلمةً
 * عربية عادية في التطبيق: «مَا» و«مِنَ» في سلّم الجمل، ولهما ملفٌّ مولَّد بحقّ. ووحدةُ
 * قاعدةِ «لا يُولَّد صوت المصحف» هي **الملف** لا السلسلة: فمنعُ توليد «مَا» لأنها وقعت
 * في سورة الفلق يمنع جملةً مشروعة، والصوابُ أن يُفصل المسار: تلاوةُ الكلمة تُخزَّن
 * بمِلَفٍّ موسوم `wbw-` (`recitation.js`) فلا تلتقي بملفّ المولَّد أبداً، ولا يُسمِع
 * الطفلَ كلمةَ المصحف إلا `recitation.play()` — يثبته اختبارُ المتصفّح بصفر طلبٍ مولَّد.
 * وهذه القائمة هي ما يتحقّق الفاحص من أنّ لكلٍّ منه تلاوةً وأنّ بيانَ التلاوة لا يعدو المصحف.
 */
export function quranWordTexts() {
  return QURAN.surahs.flatMap((s) => surahWords(s).map((w) => w.text));
}
