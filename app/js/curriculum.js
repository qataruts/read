export const storyById = (id) => STORIES.find((s) => s.id === id) || null;

/** كلمة من كلمات المنهج بنصّها المنطوق (مرجع `wordRefs` في دروس المهارات). */
export const wordBySay = (say) => GROUPS.flatMap((g) => g.words).find((w) => w.say === say) || null;

/**
 * كلمةُ منهجٍ بنصّها المشكول، في شكلِ كلمةِ معجمٍ (`word`/`emoji`/`pictured`) — أو null.
 *
 * **حوضُ خيارات سؤالِ قصةِ السورة** (حكم المدير، حزمة قصص الأنبياء): تلك القصة تقع
 * **قبل البساتين كلِّها**، فخياراتُها من كلمات المنهج لا من معجم البساتين — وصورتُها
 * من المنهج كذلك، فخياراتُ الفهم صورٌ («صدق الصورة»). ونظيرُها في الفاحص
 * `curriculum_word` بـ`check_lexicon.py`، ويقرأ كلاهما من هذا الملف لا من نسخةٍ ثانية.
 */
export function curriculumWord(text) {
  const tiled = GROUPS.flatMap((g) => g.words)
    .find((w) => w.tiles.join('') === text);
  if (tiled) return { word: text, emoji: tiled.emoji, pictured: tiled.pictured !== false };
  const imla = [...quranWordItems(),
    ...QURAN.letters.signs.flatMap((s) => s.words)].find((w) => w.read === text);
  return imla ? { word: text, emoji: imla.emoji, pictured: imla.pictured !== false } : null;
}

/**
 * كلمات درس المهارة موحَّدة الشكل: {text المعروض، say المنطوق، emoji}.
 * المُحال إليها من المنهج تُعرض بمقاطعها المركّبة وتُنطق بـsay (صوتها موجود أصلاً)،
 * والجديدة نصّها المشكول هو المعروض والمنطوق معاً.
 */
export function skillExamples(skill) {
  return [
    ...(skill.wordRefs || []).map(wordBySay).filter(Boolean)
      .map((w) => ({ text: w.tiles.join(''), say: w.say, emoji: w.emoji })),
    ...(skill.words || []).map((w) => ({ text: w.text, say: w.text, emoji: w.emoji })),
  ];
}

// ————— مفتاح قياس العلامة (حزمة «قياس العلامات») —————
//
// العلامةُ مقيسةٌ في ليتنر كسائرها، و**لا حرفَ لها**: المقيسُ فيها علامةٌ (مدٌّ، سكونٌ،
// شدّةٌ، تنوينٌ، لام) لا حرفٌ بعينه. فمفتاحُها `mark-<الدرس>` بسابقةٍ لا تلتبس بحرف —
// سابقةُ `root-<العائلة>` نفسُها في شبكات الجذور، وعلّتُها هي هي: **لا حرفَ وهميّ في
// لوحة وليّ الأمر** (حكم المدير في الحزمة ١٣، وقد صار قاعدةً).
//
// و**المفتاح لكل درسٍ لا لكل علامة**: المدّ درسان متباعدان (الألِف بعد المجموعة ١،
// والواو والياء بعد ٣). ولو جُمعا في مفتاحٍ واحد لجاز أن تسأل المراجعةُ عن «تُو/تِي»
// طفلاً لم يبلغ المجموعة الثالثة بعدُ — كسرُ المفكوكية ١٠٠٪. ومادّةُ كل تمرينٍ أزواجُ
// درسه وحدَه، فتكون مفكوكةً **بالبناء** لا بشرطٍ يُتذكَّر (حكم المدير، ١١ أغسطس ٢٠٢٦).

export const MARK_PREFIX = 'mark-';

/** مفتاحُ قياس درس علامةٍ في ليتنر — `mark-shadda` لا حرفاً. */
export const markSkillKey = (skillId) => `${MARK_PREFIX}${skillId}`;

/** هل هذا المفتاح مفتاحُ علامةٍ لا حرفاً؟ */
export const isMarkKey = (key) => String(key ?? '').startsWith(MARK_PREFIX);

/** درسُ العلامة من مفتاحه (أو null إن لم يكن مفتاحَ علامة قائمة). */
export const skillByMarkKey = (key) =>
  (isMarkKey(key) ? skillById(String(key).slice(MARK_PREFIX.length)) : null);

/**
 * وسمُ طرفٍ من طرفَي المقارنة كما يُسأل عنه: `compare.labels` تُعلن الطرفين
 * («قصير»/«ممدود»، «قمرية: تُنطق اللام»/«شمسية: تُدغَم اللام»)، وما بعد النقطتين
 * شرحٌ للعرض لا اسمٌ يُسأل به — فيُقتطع. **نصُّ واجهةٍ لا مادّة قراءة ولا نصٌّ منطوق.**
 */
export const markLabel = (label) => String(label ?? '').split(':')[0].trim();

/** نصّ الجملة كما يُعرض ويُنطق: كلماتها مفصولة بمسافة (لا مصدر ثانٍ لها). */
export const sentenceText = (sentence) => sentence.words.join(' ');

/** كل ما ينطقه درس مهارة (القاعدة، الأزواج، الكلمات). */
export function skillTexts(skill) {
  return [
    skill.rule,
    ...skill.compare.pairs.flat(),
    ...skillExamples(skill).map((w) => w.say),
  ];
}

/** كل ما تنطقه قصة (العنوان، الجمل، كلماتها). */
export function storyTexts(story) {
  return [
    story.title,
    ...story.sentences.flatMap((s) => [sentenceText(s), ...s.words]),
  ];
}

