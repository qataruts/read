export const rootOfWord = (text) => ROOTS.find((r) => r.members.includes(text)) || null;

/**
 * كلُّ ما تنطقه شاشةُ الشجرة: سطرُ المعنى وأعضاؤها.
 * **وصفرُ إضافةٍ صوتية في الأعضاء**: كلماتُ الشجرة كلماتُ المعجم والمنهج بأصواتها
 * القائمة، ولا يزيد على القائمة إلا أسطرُ المعاني الثلاثة عشر.
 */
export const rootTexts = (root) => [root.sense, ...root.members.map(memberSay)];

/**
 * مفتاحُ صوت العضو — **المعروضُ شيءٌ والمنطوقُ مفتاحُه شيء**: كلماتُ المجموعات
 * تُعرَض بمقاطعها المشكولة («دَرَسْ») ومفتاحُ ملفها نصُّها المجرَّد («درس»)، أمّا
 * كلماتُ المعجم والمرحلة القرآنية فمفتاحُها نصُّها نفسُه. فلولا هذا لطلبت الشجرةُ
 * صوتاً لا وجودَ له وصمتت على الطفل.
 */
export function memberSay(text) {
  for (const group of GROUPS) {
    for (const word of group.words) if (word.tiles.join('') === text) return word.say;
  }
  return text;
}


/** كل أزواج المواجهة مسطَّحةً: [{id, letters, after}] — مادّة التمرين في المحطة والمراجعة. */
export function contrastPairs() {
  return CONTRASTS.flatMap((c) => c.pairs.map((p) => ({ ...p, after: c.after })));
}

/**
 * كل ما تنطقه محطات «ميّز بين»: كل حرفٍ من أحرف الأزواج بالحركات الثلاث.
 * لا شيء فيها جديد — الملفات موجودة منذ الجلسة ١ (**صفر إضافة لقائمة الصوت**)،
 * وهذه القائمة هي ما تفحصه الاختبارات لتثبت ذلك.
 */
export function contrastTexts() {
  const out = [];
  for (const pair of contrastPairs()) {
    for (const letter of pair.letters) {
      for (const k of HARAKAT) out.push(letter + k.mark);
    }
  }
  return [...new Set(out)];
}

